/* POST /api/scan — free, passive Website Security Check.

   Defences, in order:
     1. Same-origin check
     2. Per-visitor rate limit (10 checks/hour per IP or IPv6 /64), counted on every post
     3. 2 KB JSON body cap, strict shape
     4. Domain validation: public domain names only (no IPs, ports, credentials, reserved names)
     5. Consent checkbox + Cloudflare Turnstile (action "scan"), verified server-side
     6. Per-target limit: results cached 15 min, and at most 3 fresh checks of one domain
        per 15 min from everyone combined, so this can't be used to hammer someone's site
     7. SSRF guard inside the scanner (every hop resolved and checked for public IPs)
     8. Optional "email me this report": validated address, max 3 emails per address per day,
        plain-text body generated by us (never visitor-supplied content)
   The scanner only makes passive GET requests and lookups — see lib/scanner.js. */
import { EMAIL_RE, emailConfigured, sendPlainEmail } from "../../lib/email.js";
import { bodyError, isSameOrigin, json, readBody } from "../../lib/http.js";
import { rateLimitSubject } from "../../lib/ip.js";
import { rateLimited } from "../../lib/ratelimit.js";
import { applyIndustry } from "../../lib/scan/advice.js";
import { formatReportText } from "../../lib/scan/report-text.js";
import { INDUSTRIES, ScanError, normalizeDomain, runScan } from "../../lib/scanner.js";
import { verifyTurnstile } from "../../lib/turnstile.js";

const VISITOR_LIMIT = { max: 10, windowSec: 60 * 60 };
const TARGET_LIMIT = { max: 3, windowSec: 15 * 60 };
const EMAIL_LIMIT = { max: 3, windowSec: 24 * 60 * 60 };
const CACHE_TTL = 15 * 60;

async function emailReport(env, request, report, to, industry) {
  if (!emailConfigured(env)) return "unavailable";
  if (await rateLimited(env, { name: "scan-email", subject: to, ...EMAIL_LIMIT })) return "limit";
  const origin = new URL(request.url).origin;
  const text = [
    formatReportText(report, { siteOrigin: origin }),
    "",
    "You (or someone using this address) asked for this report on our website.",
    "If that wasn't you, you can ignore this email; we won't email you again unless you contact us.",
  ].join("\n");
  const ok = await sendPlainEmail(env, {
    to,
    subject: `Security report for ${report.domain}: grade ${report.grade}`, // domain is a validated hostname
    text,
    replyTo: env.CONTACT_TO_EMAIL?.split(",")[0]?.trim() || undefined,
  });
  if (ok && env.CONTACT_TO_EMAIL) {
    // Lead notification for you. Plain text; values are validated or ours.
    await sendPlainEmail(env, {
      to: env.CONTACT_TO_EMAIL.split(",").map((s) => s.trim()),
      subject: `New security check lead: ${report.domain} (${report.grade})`,
      replyTo: to,
      text: [
        `Email:    ${to}`,
        `Website:  ${report.domain}`,
        `Score:    ${report.score}/100 (grade ${report.grade})`,
        `Industry: ${(industry && INDUSTRIES[industry].label) || "not given"}`,
        `Platform: ${report.platform?.label || "unknown"}`,
        "",
        "Top issues:",
        ...(report.priorities || []).map((p, i) => `${i + 1}. ${p.title}`),
      ].join("\n"),
    });
  }
  return ok ? "sent" : "failed";
}

async function handle(request, env) {
  if (!isSameOrigin(request, env)) return json({ ok: false, error: "Forbidden." }, 403);

  const ip = request.headers.get("CF-Connecting-IP") || "";
  if (await rateLimited(env, { name: "scan", subject: rateLimitSubject(ip), ...VISITOR_LIMIT })) {
    return json({ ok: false, error: "You've run several checks recently. Please try again in an hour." }, 429,
      { "Retry-After": String(VISITOR_LIMIT.windowSec) });
  }

  const { body, error } = await readBody(request, { maxBytes: 2048 });
  if (error) return bodyError(error);

  const { host, error: domainError } = normalizeDomain(body.domain);
  if (domainError) return json({ ok: false, error: domainError, fields: { domain: domainError } }, 422);
  if (body.consent !== true && body.consent !== "true" && body.consent !== "on") {
    const msg = "Please confirm this is your website (or you're allowed to check it).";
    return json({ ok: false, error: msg, fields: { consent: msg } }, 422);
  }
  const industry = typeof body.industry === "string" && Object.hasOwn(INDUSTRIES, body.industry) ? body.industry : "";
  const email = typeof body.email === "string" ? body.email.trim().toLowerCase() : "";
  if (email && (email.length > 254 || !EMAIL_RE.test(email))) {
    const msg = "Please enter a valid email address, or leave it blank.";
    return json({ ok: false, error: msg, fields: { email: msg } }, 422);
  }

  if (!(await verifyTurnstile(env, request, body["cf-turnstile-response"], ip, "scan"))) {
    return json({ ok: false, error: "Verification failed. Please try the check again." }, 403);
  }

  let report = null;
  let cached = false;
  const cacheKey = `scan:v2:${host}`;
  if (env.RATE_LIMIT_KV) {
    const hit = await env.RATE_LIMIT_KV.get(cacheKey).catch(() => null);
    if (hit) {
      try {
        report = JSON.parse(hit);
        cached = true;
      } catch {
        /* ignore a corrupt cache entry */
      }
    }
  }

  if (!report) {
    if (await rateLimited(env, { name: "scan-target", subject: host, ...TARGET_LIMIT })) {
      return json({ ok: false, error: "That website was checked a few minutes ago. Please try again in 15 minutes." }, 429,
        { "Retry-After": String(TARGET_LIMIT.windowSec) });
    }
    try {
      const origin = new URL(request.url).origin;
      report = await runScan(host, {
        userAgent: `GleydeSecurityCheck/1.0 (passive; +${origin}/security-check)`,
        safeBrowsingKey: env.GOOGLE_SAFE_BROWSING_KEY || "",
      });
    } catch (err) {
      if (err instanceof ScanError) {
        const status = err.code === "dns" ? 502 : 422;
        return json({ ok: false, error: err.message, fields: { domain: err.message } }, status);
      }
      throw err;
    }
    if (env.RATE_LIMIT_KV) {
      await env.RATE_LIMIT_KV.put(cacheKey, JSON.stringify(report), { expirationTtl: CACHE_TTL }).catch(() => {});
    }
  }

  applyIndustry(report, industry);
  const emailed = email ? await emailReport(env, request, report, email, industry) : null;
  return json({ ok: true, cached, report, emailed, emailAvailable: emailConfigured(env), verifyAvailable: Boolean(env.VERIFY_SECRET || env.RATE_LIMIT_SALT) });
}

export async function onRequestPost({ request, env }) {
  try {
    return await handle(request, env);
  } catch (err) {
    console.error("Unhandled scan error", err);
    return json({ ok: false, error: "Something went wrong running the check. Please try again later." }, 500);
  }
}

export function onRequest() {
  return json({ ok: false, error: "Method not allowed." }, 405, { Allow: "POST" });
}
